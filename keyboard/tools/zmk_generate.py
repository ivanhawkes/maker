#!/usr/bin/env python3
"""Generate the ZMK shield for the three firmware builds from the pin table and the layout.

    python tools/zmk_generate.py           # write firmware/boards/shields/split56/
    python tools/zmk_generate.py --check   # exit 1 if those files are stale
    python tools/zmk_generate.py --check-build   # after building: the built pins against pins.yaml

Inputs: pcb/pins.yaml, the same pin table the PCB generator reads, so board and firmware cannot
diverge, and layout/generated/{left,right}-hand.csv. Needs PyYAML.

The keymap and user settings in firmware/config/ are edited by hand and not touched here.
Written against ZMK at the commit pinned in firmware/config/west.yml; firmware/README.md
has the build commands. Nothing here has run on hardware.
"""

from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SHIELD = "split56"   # stands for the moment (owner, 2026-11-23); also the shield directory
NAME = "Split56"     # USB and BLE name, 16 characters at most
OUT = ROOT / "firmware" / "boards" / "shields" / SHIELD
U = 19.05            # one key unit, mm
ROWS = ["R1", "R2", "R3", "R4"]
COLS = ["C0", "C1", "C2", "C3", "C4", "C5", "T"]
TALL_THUMBS = ("T2", "T3")  # 1.5u caps fitted with the long side along the finger (docs/decisions.md)
HEADER = "Generated by tools/zmk_generate.py from pcb/pins.yaml and layout/generated/. Do not edit."
# Lighting times (owner, 2026-11-24): a half's lighting is full for HOLD_MS after its last key
# press, then fades to black over FADE_OUT_MS; it lights from black to full over FADE_IN_MS.
HOLD_MS, FADE_IN_MS, FADE_OUT_MS = 60000, 50, 5000


def read_keys(side: str) -> dict[str, dict]:
    with (ROOT / "layout" / "generated" / f"{side}-hand.csv").open() as f:
        return {k["id"]: k for k in csv.DictReader(f)}


def keymap_order(left: dict, right: dict) -> list[tuple[str, dict]]:
    """Each finger row across both halves, outer pinky to outer pinky, then the thumbs."""
    rows = [[("L", left[f"C{c}{r}"]) for c in range(6)] + [("R", right[f"C{c}{r}"]) for c in reversed(range(6))]
            for r in ROWS]
    rows.append([("L", left[f"T{t}"]) for t in range(4)] + [("R", right[f"T{t}"]) for t in reversed(range(4))])
    for row in rows:  # the order is read off the ids; the geometry must agree, left to right
        for half in "LR":
            xs = [float(k["x_mm"]) for s, k in row if s == half]
            assert xs == sorted(xs), f"keys not in left-to-right order: {[k['id'] for s, k in row if s == half]}"
    return [key for row in rows for key in row]


def matrix_rc(pins: dict, side: str, key: dict) -> tuple[int, int]:
    row = pins["thumb_rows"][key["id"]] if key["group"] == "T" else key["row"]
    return ROWS.index(row), COLS.index(key["group"]) + (len(COLS) if side == "R" else 0)


def pro_micro(pins: dict, pad: int) -> int:
    """Pro Micro pin number of a controller pad: ZMK's &pro_micro uses the Arduino D numbers."""
    name = pins["controller"]["pads"][pad][0]
    assert name[0] == "D" and name[1:].isdigit(), f"pad {pad} ({name}) is not a GPIO"
    return int(name[1:])


def port_pin(pins: dict, pad: int) -> tuple[int, int]:
    gpio = pins["controller"]["pads"][pad][2]  # "P0.11"
    return int(gpio[1]), int(gpio[3:])


def physical_keys(order: list[tuple[str, dict]]) -> list[str]:
    """ZMK key_physical_attrs: w h x y rot rx ry, in hundredths of a key unit and of a degree,
    y downwards, x and y the top-left corner, rotation clockwise about the key centre."""
    left_x = [float(k["x_mm"]) for s, k in order if s == "L"]
    right_x = [float(k["x_mm"]) for s, k in order if s == "R"]
    shift = max(left_x) - min(right_x) + 2 * U  # one key's gap between the halves
    top = max(float(k["y_mm"]) for _, k in order)
    out = []
    for side, k in order:
        cx = (float(k["x_mm"]) + (shift if side == "R" else 0.0) - min(left_x)) / U + 1.0  # 1u margin
        cy = (top - float(k["y_mm"])) / U + 1.0
        w, h = 100, 150 if k["id"] in TALL_THUMBS else 100
        x, y = round(cx * 100 - w / 2), round(cy * 100 - h / 2)
        rot = round(-float(k["rotation_deg"]) * 100)  # the layout turns anticlockwise, ZMK clockwise
        assert x >= 0 and y >= 0, k["id"]
        out.append(f"<&key_physical_attrs {w} {h} {x:4d} {y:4d} {f'({rot})' if rot < 0 else rot:>7} {round(cx * 100):4d} {round(cy * 100):4d}>"
                   f"  // {side} {k['id']}")
    return out


def files() -> dict[str, str]:
    pins = yaml.safe_load((ROOT / "pcb" / "pins.yaml").read_text())
    left, right = read_keys("left"), read_keys("right")
    order = keymap_order(left, right)
    rcs = [matrix_rc(pins, s, k) for s, k in order]
    assert len(order) == 56 and len(set(rcs)) == 56, "every key needs its own matrix position"
    assert len(left) == len(right)

    def gpios(pads, flags):
        return "\n            , ".join(f"<&pro_micro {pro_micro(pins, p)} {flags}>" for p in pads)

    # One line per keymap row: 12 keys for each finger row, then the 8 thumbs.
    cells = [f"RC({r},{c})" for r, c in rcs]
    map_rows = ["  ".join(f"{c:9s}" for c in cells[i:i + 12]).rstrip() for i in range(0, 48, 12)]
    map_rows.append("  ".join(f"{c:9s}" for c in cells[48:]).rstrip())
    keys = physical_keys(order)
    port, pin = port_pin(pins, pins["led_data"])
    en = pro_micro(pins, pins["led_power_enable"])
    up = SHIELD.upper()
    strip = f"""&pinctrl {{
    spi3_default: spi3_default {{
        group1 {{
            psels = <NRF_PSEL(SPIM_MOSI, {port}, {pin})>;
        }};
    }};

    spi3_sleep: spi3_sleep {{
        group1 {{
            psels = <NRF_PSEL(SPIM_MOSI, {port}, {pin})>;
            low-power-enable;
        }};
    }};
}};

&spi3 {{
    compatible = "nordic,nrf-spim";
    status = "okay";

    pinctrl-0 = <&spi3_default>;
    pinctrl-1 = <&spi3_sleep>;
    pinctrl-names = "default", "sleep";

    led_strip: ws2812@0 {{
        compatible = "worldsemi,ws2812-spi";

        /* SPI */
        reg = <0>; /* ignored, but necessary for SPI bindings */
        spi-max-frequency = <4000000>;

        /* SK6812MINI-E: WS2812 protocol, green first (datasheet) */
        chain-length = <%d>;
        spi-one-frame = <0x70>;
        spi-zero-frame = <0x40>;
        color-mapping = <LED_COLOR_ID_GREEN LED_COLOR_ID_RED LED_COLOR_ID_BLUE>;
    }};
}};
"""
    out = {}
    out["Kconfig.shield"] = f"""# {HEADER}

config SHIELD_{up}_LEFT
    def_bool $(shields_list_contains,{SHIELD}_left)

config SHIELD_{up}_RIGHT
    def_bool $(shields_list_contains,{SHIELD}_right)

config SHIELD_{up}_DONGLE
    def_bool $(shields_list_contains,{SHIELD}_dongle)
"""
    out["Kconfig.defconfig"] = f"""# {HEADER}
#
# The dongle is the split central and both halves are peripherals (docs/decisions.md).

if SHIELD_{up}_DONGLE

config ZMK_KEYBOARD_NAME
    default "{NAME}"

config ZMK_SPLIT_ROLE_CENTRAL
    default y

config ZMK_SPLIT_BLE_CENTRAL_PERIPHERALS
    default 2

# The peripherals plus ZMK's five host profiles (ZMK dongle guide).
config BT_MAX_CONN
    default 7

config BT_MAX_PAIRED
    default 7

if ZMK_DISPLAY

config I2C
    default y

config SSD1306
    default y

endif # ZMK_DISPLAY

endif

if SHIELD_{up}_LEFT || SHIELD_{up}_RIGHT || SHIELD_{up}_DONGLE

config ZMK_SPLIT
    default y

endif

if SHIELD_{up}_LEFT || SHIELD_{up}_RIGHT

# The halves run on batteries: deep sleep after ZMK's idle-sleep timeout. A key press wakes them.
config ZMK_SLEEP
    default y

endif
"""
    out[f"{SHIELD}.zmk.yml"] = f"""# {HEADER}
file_format: "1"
id: {SHIELD}
name: {NAME}
type: shield
requires: [pro_micro]
features:
  - keys
  - underglow
siblings:
  - {SHIELD}_left
  - {SHIELD}_right
  - {SHIELD}_dongle
"""
    out[f"{SHIELD}.dtsi"] = f"""/* {HEADER} */

/*
 * The matrix transform and physical layout, the same in all three parts.
 * Matrix: {len(ROWS)} rows by {len(COLS)} columns a half ({', '.join(COLS)}); the right half is offset by {len(COLS)} columns.
 * Key order: each finger row from the left outer pinky to the right outer pinky, then the
 * thumbs, left T0..T3 and right T3..T0.
 */

#include <dt-bindings/zmk/matrix_transform.h>
#include <physical_layouts.dtsi>

/ {{
    chosen {{
        zmk,physical-layout = &physical_layout0;
    }};

    default_transform: keymap_transform_0 {{
        compatible = "zmk,matrix-transform";
        columns = <{2 * len(COLS)}>;
        rows = <{len(ROWS)}>;
        map = <
{chr(10).join(map_rows)}
        >;
    }};

    physical_layout0: physical_layout_0 {{
        compatible = "zmk,physical-layout";
        display-name = "Default";
        transform = <&default_transform>;
        keys  //                 w   h    x    y     rot   rx   ry
            = {(chr(10) + "            , ").join(keys)}
            ;
    }};
}};
"""
    out[f"{SHIELD}_half.dtsi"] = f"""/* {HEADER} */

/* What both halves share: the key matrix, the LED chain and the LED supply switch. */

#include "{SHIELD}.dtsi"
#include <dt-bindings/led/led.h>

/ {{
    chosen {{
        zmk,kscan = &kscan0;
        zmk,underglow = &led_fade;
    }};

    kscan0: kscan {{
        compatible = "zmk,kscan-gpio-matrix";
        wakeup-source;

        diode-direction = "col2row";
        row-gpios  // {', '.join(ROWS)}
            = {gpios([pins["rows"][r] for r in ROWS], "(GPIO_ACTIVE_HIGH | GPIO_PULL_DOWN)")}
            ;
        col-gpios  // {', '.join(COLS)}
            = {gpios([pins["columns"][c] for c in COLS], "GPIO_ACTIVE_HIGH")}
            ;
    }};

    /*
     * The board's external power node (same name, so this extends it). LED_EN on the PCB
     * switches the LED supply; P0.13 is the module's own 3.3 V output, as on a stock
     * nice!nano, which nothing on this PCB uses.
     */
    EXT_POWER {{
        control-gpios = <&pro_micro {en} GPIO_ACTIVE_HIGH>, <&gpio0 13 GPIO_ACTIVE_HIGH>;
    }};

    /*
     * The lighting goes through this to the LED chain (firmware/src/led_strip_fade.c): black
     * to full over fade-in-ms when it lights, and full to black over the last fade-out-ms
     * before ZMK's idle timeout, which then switches the lighting and its supply off.
     */
    led_fade: led_fade {{
        compatible = "led-strip-fade";
        led-strip = <&led_strip>;
        chain-length = <{len(left)}>;
        fade-in-ms = <{FADE_IN_MS}>;
        fade-out-ms = <{FADE_OUT_MS}>;
    }};
}};

{strip % len(left)}"""
    out[f"{SHIELD}_left.overlay"] = f"""/* {HEADER} */

#include "{SHIELD}_half.dtsi"
"""
    out[f"{SHIELD}_right.overlay"] = f"""/* {HEADER} */

#include "{SHIELD}_half.dtsi"

&default_transform {{
    col-offset = <{len(COLS)}>;
}};
"""
    half_conf = f"""# {HEADER}
#
# LED limits from the electrical review (docs/pcb.md). The power switch is rated 0.3 A and
# {len(left)} LEDs at 20 % white draw about 0.23 A, so do not raise the cap without changing the board.
# firmware/config/ is merged after this file and could: firmware/src/led_strip_fade.c stops
# the build if the cap is above 20.
CONFIG_ZMK_RGB_UNDERGLOW=y
CONFIG_ZMK_RGB_UNDERGLOW_BRT_MAX=20
# The LED supply follows the lighting: off when the lighting is off or the half is idle.
CONFIG_ZMK_RGB_UNDERGLOW_EXT_POWER=y
CONFIG_ZMK_RGB_UNDERGLOW_AUTO_OFF_IDLE=y
CONFIG_ZMK_RGB_UNDERGLOW_ON_START=n
# A half is idle {HOLD_MS // 1000} s after its last key press plus the {FADE_OUT_MS // 1000} s fade to black, so the
# fade ends as ZMK switches the lighting off.
CONFIG_ZMK_IDLE_TIMEOUT={HOLD_MS + FADE_OUT_MS}
"""
    out[f"{SHIELD}_left.conf"] = half_conf
    out[f"{SHIELD}_right.conf"] = half_conf
    out[f"{SHIELD}_dongle.conf"] = f"""# {HEADER}
#
# The dongle has no LEDs, but ZMK only relays a lighting key to the halves if the lighting
# behaviour exists on the central, so it is built in here with a one-LED strip on an unused pin.
# Its external power output feeds the display, so lighting must not switch it.
CONFIG_ZMK_RGB_UNDERGLOW=y
CONFIG_ZMK_RGB_UNDERGLOW_EXT_POWER=n
CONFIG_ZMK_RGB_UNDERGLOW_ON_START=n
# The display blanks after this long without a key press.
CONFIG_ZMK_IDLE_TIMEOUT={HOLD_MS}
"""
    out[f"{SHIELD}_dongle.overlay"] = f"""/* {HEADER} */

/*
 * The desk dongle: the split central, with no keys of its own. Build it with the display
 * shield: "{SHIELD}_dongle dongle_display".
 */

#include "{SHIELD}.dtsi"
#include <dt-bindings/led/led.h>

/ {{
    chosen {{
        zmk,kscan = &mock_kscan;
        zephyr,display = &oled;
        zmk,underglow = &led_strip;
    }};

    mock_kscan: mock_kscan_0 {{
        compatible = "zmk,kscan-mock";
        columns = <0>;
        rows = <0>;
        events = <0>;
    }};
}};

/*
 * The common 0.96 in 128 x 64 SSD1306 I2C module (owner, 2026-11-23) on the Pro Micro I2C pins
 * (D2 SDA, D3 SCL). The properties are the usual ones for it: check them on the part.
 */
&pro_micro_i2c {{
    status = "okay";

    oled: ssd1306@3c {{
        compatible = "solomon,ssd1306fb";
        reg = <0x3c>;
        width = <128>;
        height = <64>;
        segment-offset = <0>;
        page-offset = <0>;
        display-offset = <0>;
        multiplex-ratio = <63>;
        segment-remap;
        com-invdir;
        inversion-on;
        prechargep = <0x22>;
    }};
}};

/* The one-LED strip that keeps the lighting behaviour on the central (see {SHIELD}_dongle.conf). */
{strip % 1}"""
    return out


def check_build() -> int:
    """Compare what the builds resolved with pcb/pins.yaml: an end-to-end check of the pin mapping.

    Reads the devicetree and Kconfig that ZMK's build wrote for each half and for the dongle
    (firmware/workspace/build/{left,right,dongle}/zephyr/). The Pro Micro pin numbers are resolved
    to nRF GPIOs through the board's own gpio-map, so this also tests the GPIO column of pins.yaml
    against ZMK's board definition.
    """
    pins = yaml.safe_load((ROOT / "pcb" / "pins.yaml").read_text())
    pads = pins["controller"]["pads"]
    bad = []

    def want(pad):
        return pads[pad][2]

    def config(part):
        text = (ROOT / "firmware" / "workspace" / "build" / part / "zephyr" / ".config").read_text()
        return dict(m.groups() for m in re.finditer(r"^(CONFIG_\w+)=(.*)$", text, re.M))

    for part in ("left", "right"):
        dts = (ROOT / "firmware" / "workspace" / "build" / part / "zephyr" / "zephyr.dts").read_text()
        gmap = re.search(r"pro_micro: [^{]*\{.*?gpio-map = ([^;]*);", dts, re.S).group(1)
        to_gpio = {int(d, 16): f"P{port}.{int(pin, 16):02d}"
                   for d, port, pin in re.findall(r"< (0x[0-9a-f]+) 0x0 &gpio(\d) (0x[0-9a-f]+) 0x0 >", gmap)}

        def resolved(node, prop):
            body = re.search(node + r" \{.*?" + prop + r" = ([^;]*);", dts, re.S).group(1)
            out = [to_gpio[int(n, 16)] for n in re.findall(r"&pro_micro (0x[0-9a-f]+)", body)]
            return out + [f"P{port}.{int(pin, 16):02d}" for port, pin in re.findall(r"&gpio(\d) (0x[0-9a-f]+)", body)]

        psel = int(re.search(r"spi3_default \{.*?psels = < (0x[0-9a-f]+) >", dts, re.S).group(1), 16)
        got = {
            "rows": resolved("kscan0: kscan", "row-gpios"),
            "columns": resolved("kscan0: kscan", "col-gpios"),
            "LED supply enable": resolved("EXT_POWER", "control-gpios")[:1],
            "LED data": [f"P{(psel >> 5) & 1}.{psel & 31:02d}"],
            "LED count": [int(re.search(r"led_strip: .*?chain-length = < (0x[0-9a-f]+) >", dts, re.S).group(1), 16)],
            "column offset": [int(m.group(1), 16) if (m := re.search(r"col-offset = < (0x[0-9a-f]+) >", dts)) else 0],
        }
        expect = {
            "rows": [want(pins["rows"][r]) for r in ROWS],
            "columns": [want(pins["columns"][c]) for c in COLS],
            "LED supply enable": [want(pins["led_power_enable"])],
            "LED data": [want(pins["led_data"])],
            "LED count": [len(read_keys(part))],
            "column offset": [0 if part == "left" else len(COLS)],
        }
        for name in expect:
            if got[name] != expect[name]:
                bad.append(f"{part} {name}: built {got[name]}, pins.yaml {expect[name]}")
        cfg = config(part)
        if cfg.get("CONFIG_ZMK_SPLIT") != "y" or cfg.get("CONFIG_ZMK_SPLIT_ROLE_CENTRAL") == "y":
            bad.append(f"{part}: not a split peripheral")
        if int(cfg.get("CONFIG_ZMK_RGB_UNDERGLOW_BRT_MAX", "100")) > 20 or cfg.get("CONFIG_ZMK_RGB_UNDERGLOW_AUTO_OFF_IDLE") != "y":
            bad.append(f"{part}: LED cap {cfg.get('CONFIG_ZMK_RGB_UNDERGLOW_BRT_MAX')}, idle-off {cfg.get('CONFIG_ZMK_RGB_UNDERGLOW_AUTO_OFF_IDLE')}")
        fade = [int(m.group(1), 16) if (m := re.search(r"led_fade: .*?" + p + r" = < (0x[0-9a-f]+) >", dts, re.S)) else None
                for p in ("fade-in-ms", "fade-out-ms")]
        idle = int(cfg.get("CONFIG_ZMK_IDLE_TIMEOUT", "0"))
        if not re.search(r"zmk,underglow = &led_fade;", dts) or fade != [FADE_IN_MS, FADE_OUT_MS] or idle != HOLD_MS + FADE_OUT_MS:
            bad.append(f"{part}: lighting not through the fade, or its times differ: fade {fade} ms, idle timeout {idle} ms")
        print(f"{part}: rows {got['rows']}, columns {got['columns']}, LED data {got['LED data'][0]}, "
              f"LED enable {got['LED supply enable'][0]}, {got['LED count'][0]} LEDs, "
              f"brightness cap {cfg.get('CONFIG_ZMK_RGB_UNDERGLOW_BRT_MAX')} %, "
              f"fade in {fade[0]} ms, out {fade[1]} ms, ending at the idle timeout, {idle} ms")
    cfg = config("dongle")
    if cfg.get("CONFIG_ZMK_SPLIT_ROLE_CENTRAL") != "y" or cfg.get("CONFIG_ZMK_SPLIT_BLE_CENTRAL_PERIPHERALS") != "2":
        bad.append("dongle: not a central for two peripherals")
    print(f"dongle: central for {cfg.get('CONFIG_ZMK_SPLIT_BLE_CENTRAL_PERIPHERALS')} peripherals, "
          f"display {cfg.get('CONFIG_ZMK_DISPLAY', 'n')}")
    for b in bad:
        print("FAILED", b)
    return 1 if bad else 0


def main() -> int:
    if sys.argv[1:] == ["--check-build"]:
        return check_build()
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] and not check:
        raise SystemExit(__doc__)
    want = files()
    stale = [n for n, text in want.items() if not (OUT / n).exists() or (OUT / n).read_text() != text]
    stale += [f"{p.name} (not generated)" for p in OUT.glob("*") if p.is_file() and p.name not in want] if OUT.exists() else []
    if check:
        print("firmware shield:", "up to date" if not stale else f"STALE: {', '.join(stale)}")
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in want.items():
        (OUT / name).write_text(text)
    print(f"wrote {len(want)} files to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
